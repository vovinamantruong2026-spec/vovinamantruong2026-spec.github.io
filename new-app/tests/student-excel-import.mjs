import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
import {readStudentExcel, previewStudentExcel} from '../src/student-excel-import.ts';
import {createWorkbook} from '../src/xlsx-export.ts';

const workbook = new ExcelJS.Workbook();
const sheet = workbook.addWorksheet('Võ sinh');
sheet.addRow(['Mã võ sinh','Họ và tên','Lớp','Ngày sinh','Điện thoại']);
sheet.addRow(['VVN.0001','Nguyễn Văn A','Lớp A',new Date('2012-05-06T00:00:00Z'),'0123456789']);
sheet.addRow(['','Võ sinh mới','Lớp A','07/04/2014','']);
const file = bytes => ({name:'test.xlsx',size:bytes.byteLength,arrayBuffer:async () => bytes});
const rows = await readStudentExcel(file(await workbook.xlsx.writeBuffer()));
const cls = {kind:'class',id:'class-a',data:{name:'Lớp A'},version:1};
const student = {kind:'student',id:'student-a',data:{id:'VVN.0001',name:'Nguyễn Văn A',classId:cls.id,avatarFile:{id:'photo-a'}},version:4};
const today = '2026-11-20';
const preview = previewStudentExcel(rows,[student],[cls],today);
assert.equal(preview[0].write.version,4);
assert.equal(preview[0].write.data.phone,'0123456789');
assert.equal(preview[0].write.data.dob,'2012-05-06');
assert.equal(preview[0].write.data.avatarFile.id,'photo-a');
assert.equal(preview[1].write.version,0);
assert.equal(preview[1].write.data.id,'');
assert.equal(preview[1].write.data.dob,'2014-04-07');
assert.match(previewStudentExcel([{...rows[1],className:'Lớp khác'}],[],[cls],today)[0].error,/phạm vi/);
assert.match(previewStudentExcel([rows[1],{...rows[1],row:4}],[],[cls],today)[1].error,/Trùng/);
assert.match(previewStudentExcel([{...rows[1],dob:'31/02/2014'}],[],[cls],today)[0].error,/Ngày sinh/);
const oldExport = await createWorkbook([{name:'Võ sinh',headers:['Họ và tên','Lớp','Mã võ sinh'],rows:[['Nguyễn Văn A','Lớp A','VVN.0001']]}]);
assert.equal((await readStudentExcel(file(oldExport)))[0].code,'VVN.0001');
sheet.getCell('B3').value = {formula:'"x"',result:'x'};
await assert.rejects(readStudentExcel(file(await workbook.xlsx.writeBuffer())),/công thức/);
console.log('PASS: XLSX, existing export, class scope, update, new record, dates, duplicates and formulas');
